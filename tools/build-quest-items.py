#!/usr/bin/env python3
"""Builds quest-items.json from tools/quest-items-source.py.

Usage, from the repository root:
  git clone --depth 1 https://github.com/runelite/runelite tools/runelite
  python3 tools/build-quest-items.py tools/runelite/runelite-api/src/main/java/net/runelite/api/gameval/ItemID.java

Each item name from the wiki is matched to the in-game name RuneLite's gameval ItemID gives every constant in its
comment. Every id with that name counts (a potion's doses included), so the plugin can find the item in the bank by
id. A name that matches nothing stops the build.
"""
import json
import os
import re
import sys

GROUPS = {
    'axe': ['Bronze axe', 'Iron axe', 'Steel axe', 'Black axe', 'Mithril axe', 'Adamant axe', 'Rune axe',
            'Dragon axe', 'Infernal axe', 'Crystal axe', 'Gilded axe'],
    'pickaxe': ['Bronze pickaxe', 'Iron pickaxe', 'Steel pickaxe', 'Black pickaxe', 'Mithril pickaxe',
                'Adamant pickaxe', 'Rune pickaxe', 'Dragon pickaxe', 'Infernal pickaxe', 'Crystal pickaxe',
                'Gilded pickaxe'],
}
GROUP_TITLES = {'axe': 'Any axe', 'pickaxe': 'Any pickaxe'}
# Names the wiki and the gameval comment spell differently, with the id both give.
SPECIAL = {
    # Several items are named Coins (minigame and quest tokens among them); only 995 is money.
    'Coins': [995],
    # gameval calls 1281 "Steel shortsword"; the wiki's Steel sword infobox gives item ID 1281.
    'Steel sword': [1281],
}


def names(path):
    """Item ids by in-game name, from the name RuneLite's gameval ItemID gives each constant."""
    out = {}
    for m in re.finditer(r'/\*\*\s*\n\s*\* (.+?)\s*\n\s*\*/\s*\n\s*public static final int \w+ = (\d+);',
                         open(path).read()):
        out.setdefault(m.group(1).strip().lower(), []).append(int(m.group(2)))
    return out


def ids_for(name, table):
    if name in SPECIAL:
        return SPECIAL[name]
    key = name.lower()
    found = list(table.get(key, []))
    if not re.search(r'\(\d\)$', key):
        # A potion's doses each have their own id: "Stamina potion" is any of (1) to (4).
        for dose in range(1, 5):
            found += table.get('%s(%d)' % (key, dose), [])
    return sorted(set(found))


def parse(line, table, errors, quest):
    note = None
    if '|' in line:
        line, note = line.split('|', 1)
        note = note.strip()
    line = line.strip()
    during = '~' in line
    unchecked = line.endswith('?') or ' ?' in line
    line = line.replace('~', '').replace('?', '').strip()
    names = [n.strip() for n in line.split('/')]
    qty = 1
    for i, n in enumerate(names):
        m = re.match(r'^(.*?) x(\d+)$', n)
        if m:
            names[i], qty = m.group(1).strip(), int(m.group(2))
    ids = []
    shown = []
    for n in names:
        g = re.fullmatch(r'<(\w+)>', n)
        if g:
            shown.append(GROUP_TITLES[g.group(1)])
            for member in GROUPS[g.group(1)]:
                found = ids_for(member, table)
                if not found:
                    errors.append(quest + ': ' + member)
                ids += found
            continue
        shown.append(n)
        if unchecked:
            continue
        found = ids_for(n, table)
        if not found:
            errors.append(quest + ': ' + n)
        ids += found
    item = {'name': shown[0], 'qty': qty}
    if len(shown) > 1:
        item['or'] = shown[1:]
    if not unchecked:
        item['ids'] = sorted(set(ids))
    if during:
        item['duringQuest'] = True
    if note:
        item['note'] = note
    return item


def main(itemid_path):
    here = os.path.dirname(os.path.abspath(__file__))
    scope = {}
    exec(open(os.path.join(here, 'quest-items-source.py')).read(), scope)
    table = names(itemid_path)
    errors = []
    out = {
        'source': 'Generated by tools/build-quest-items.py from the OSRS Wiki quest pages. Do not hand-edit.',
        'quests': {},
    }
    for quest, rows in scope['QUESTS'].items():
        out['quests'][quest] = {
            'items': [parse(l, table, errors, quest) for l in rows['items']],
            'recommended': [parse(l, table, errors, quest) for l in rows['recommended']],
        }
    if errors:
        sys.exit('No ItemID for:\n  ' + '\n  '.join(errors))
    dest = os.path.join(here, '..', 'src', 'main', 'resources', 'com', 'codex', 'navigator', 'quest-items.json')
    with open(dest, 'w') as f:
        json.dump(out, f, indent=1, ensure_ascii=False)
        f.write('\n')


if __name__ == '__main__':
    main(sys.argv[1])
