#!/usr/bin/env python3
"""Builds src/main/resources/com/codex/navigator/sea-charts.tsv and seas.tsv.

Usage:
  build-sea-charting.py sea-charts.tsv seas.tsv dump.dbrow sea-charting/wiki-sea-pages.tsv ChartingTasksData.java

Sources:
- dump.dbrow: the game cache's db rows (github.com/Joshua-F/osrs-dumps, config/dump.dbrow). Its
  sailing_charting_core table has every chart task (358 rows) with its unique_id, hint, sea and kind; the game's
  varbit for a task is 18574 + unique_id, which matches RuneLite's gameval SAILING_CHARTING_*_COMPLETE names for
  357 of them (the 358th, porth_gwenith weather, is gameval's WEATHER_TROLL_VAGABONDS_REST_COMPLETE, 18741).
  Sea centres and oceans come from its sailing_sea table (unconfirmed: not on the wiki).
- sea-charting/wiki-sea-pages.tsv: each sea's OSRS Wiki page, its charting table copied by hand (level, kind, task).
  Task text and level come from here. Western Gate's page leaves levels blank.
- ChartingTasksData.java: Quest Helper's chart list (BSD-2), used only for the levels the wiki leaves blank,
  marked "qh" (unconfirmed).
"""
import re, sys, json


def parse_dbrow(path):
    rows = {}
    cur = None
    for line in open(path, encoding='utf-8'):
        line = line.rstrip('\n')
        m = re.match(r'^\[(.+)\]$', line)
        if m:
            cur = {'_name': m.group(1)}
            rows[m.group(1)] = cur
            continue
        if cur is None:
            continue
        if line.startswith('table='):
            cur['_table'] = line[6:]
        elif line.startswith('data='):
            k, v = line[5:].split(',', 1)
            cur.setdefault(k, []).append(v)
    return rows


import json,re,sys
r=parse_dbrow(sys.argv[3])
core=[v for v in r.values() if v.get('_table')=='sailing_charting_core']
TYPES={'sailing_charting_generic':'GENERIC','sailing_charting_spyglass':'SPYGLASS','sailing_charting_current_duck':'CURRENT','sailing_charting_drink_crate':'CRATE','sailing_charting_mermaid_guide':'DIVING','sailing_charting_weather_troll':'WEATHER'}
W2T={'Generic':'GENERIC','Spyglass':'SPYGLASS','Current':'CURRENT','Crate':'CRATE','Diving':'DIVING','Weather':'WEATHER'}
def norm(s): return re.sub(r'[^a-z0-9]','',s.lower().replace('beware of','|').split('|')[0])
wiki=[l.rstrip('\n').split('\t') for l in open(sys.argv[4],encoding='utf-8')]
# manual pairs: cache hint prefix -> wiki text prefix (wording differs slightly between game and wiki)
MANUAL={
 'Find a sealed crate north of the cathedral on Wyrmscraig.':'Find a Sealed crate north of the cathedral on Wyrmscraig and sample the contents.',
 'Use your spyglass to get a good view of the temple in the Avium Savannah from the south.':'Use your spyglass to get a good view of the south eastern temple in the Avium Savannah from the south.',
 'Find some interesting sea life in the middle of the Western Gate.':'Find some some interesting sea life in the middle of the Western Gate.',
 'With help from a mermaid guide, document the water depth south west of Lunar Isle.':'With help from a mermaid guide, document the water depth in the south west of Lunar Isle.',
}
# levels the sea pages leave blank: Quest Helper's ChartingTasksData (unconfirmed)
QH={'Test the currents east of Minotaurs\' Rest.':22}
qh={}
for l in open(sys.argv[5],encoding='utf-8'):
    for m in re.finditer(r'ChartingType\.(\w+), "((?:[^"\\]|\\.)*)".*?, (\d+), VarbitID\.(\w+)',l):
        qh[m.group(4)]=int(m.group(3))
seas={k:v for k,v in r.items() if v.get('_table')=='sailing_sea'}
rows=[];seaused={}
for c in sorted(core,key=lambda c:int(c['unique_id'][0])):
    uid=int(c['unique_id'][0]); varbit=18574+uid
    loc=seas[c['sailing_sea_secondary'][0]] if 'sailing_sea_secondary' in c else seas[c['sailing_sea'][0]]
    typ=TYPES[c['charting_type'][0]]
    h=c['hint'][0]
    target=MANUAL.get(h,h)
    m=[w for w in wiki if norm(w[3])==norm(target) and w[0]==loc['name'][0]]
    assert len(m)<=1,(h,m)
    if m:
        w=m[0]; assert W2T[w[2]]==typ,(w,typ)
        text=w[3]; src='wiki'
        if 'some some' in text: text=h
        if w[1]=='?':
            if 'Minotaurs' in text: level=22; src='wiki'  # Sea charting/Current
            else: level=qh[c['_name'][:-5].upper()+'_COMPLETE']; src='qh'
        else: level=int(w[1])
    else:
        assert loc['name'][0]=='Great Sound',h
        text=h; 
        if typ=='CURRENT': level=22; src='wiki'  # Sea charting/Current: Level 22 "Test the currents south of Lacerta Falls."
        else: level=qh[c['_name'][:-5].upper()+'_COMPLETE']; src='qh'
        text=text[0].upper()+text[1:]
        text=text.replace('sealed crate','Sealed crate')
    seaused[loc['_name']]=loc
    rows.append((varbit,typ,level,src,loc['name'][0],text,c['_name'][:-5]))
assert len(rows)==358
out=open(sys.argv[1],'w',encoding='utf-8')
out.write('# Sea charting: every chart task, one per line. Generated by tools/build-sea-charting.py; see that file for sources.\n')
out.write('# varbit\ttype\tlevel\tlevel source (wiki = OSRS Wiki sea page; qh = unconfirmed, Quest Helper)\tsea\ttask\n')
for row in rows: out.write('%d\t%s\t%d\t%s\t%s\t%s\n'%row[:6])
out.close()
o2=open(sys.argv[2],'w',encoding='utf-8')
o2.write('# Seas with charts: name, ocean, and the centre the game cache gives (unconfirmed: game cache dump, Joshua-F/osrs-dumps).\n')
o2.write('# sea\tocean\tx\ty\n')
for k,s in sorted(seaused.items(),key=lambda kv:int(kv[1]['unique_id'][0])):
    lv,mx,mz,lx,lz=map(int,s['centre_coord'][0].split('_'))
    o2.write('%s\t%s\t%d\t%d\n'%(s['name'][0],seas[s['ocean'][0]]['name'][0],mx*64+lx,mz*64+lz))
o2.close()
import collections
print(collections.Counter(x[3] for x in rows), collections.Counter(x[1] for x in rows), len(seaused))
for x in rows:
    if x[3]=='qh': print(x)
