#!/usr/bin/env python3
"""Lists the quest skill requirements that a temporary boost can meet, as boosts.json.

Quest Helper (BSD 2-Clause, see THIRD_PARTY_NOTICES.md) marks a requirement that can be boosted with
`new SkillRequirement(Skill.X, level, true)`. Only those explicit marks are taken: a requirement Quest
Helper leaves unmarked may or may not be boostable, so the Codex never calls it boostable.

Usage, from the repository root:
  git clone --depth 1 https://github.com/Zoinkwiz/quest-helper tools/quest-helper
  git clone --depth 1 https://github.com/runelite/runelite tools/runelite
  python3 tools/build-boosts.py tools/quest-helper tools/runelite

A mark is kept only when the bundled codex-data.json asks for the same skill at the same level, so a
quest whose requirement has since changed loses its mark rather than carrying a stale one.
"""
import json
import os
import re
import sys

DATA = 'src/main/resources/com/codex/navigator/codex-data.json'
OUT = 'src/main/resources/com/codex/navigator/boosts.json'

ENUM_ROW = re.compile(r'^\s+[A-Z_0-9]+\(new ([A-Za-z0-9]+)\(\),\s*Quest\.([A-Z_0-9]+)', re.M)
QUEST_NAME = re.compile(r'^\s+([A-Z_0-9]+)\(\d+,\s*"((?:[^"\\]|\\.)*)"\)', re.M)
SKILL_REQ = re.compile(r'new SkillRequirement\(Skill\.([A-Z]+),\s*(\d+),\s*(true|false)')


def main(quest_helper, runelite):
    qh_src = os.path.join(quest_helper, 'src/main/java/com/questhelper')
    enum_text = open(os.path.join(qh_src, 'questinfo/QuestHelperQuest.java'), encoding='utf-8').read()
    quest_text = open(os.path.join(runelite, 'runelite-api/src/main/java/net/runelite/api/Quest.java'),
                      encoding='utf-8').read()
    names = {k: v.replace('\\"', '"') for k, v in QUEST_NAME.findall(quest_text)}

    files = {}
    for root, _, entries in os.walk(os.path.join(qh_src, 'helpers')):
        for entry in entries:
            if entry.endswith('.java'):
                files[entry[:-5]] = os.path.join(root, entry)

    marks = {}
    for cls, enum in ENUM_ROW.findall(enum_text):
        name = names.get(enum)
        path = files.get(cls)
        if name is None or path is None:
            continue
        seen = {}
        for skill, level, boost in SKILL_REQ.findall(open(path, encoding='utf-8').read()):
            key = (skill.title(), int(level))
            # A requirement marked both ways in one helper is ambiguous; it is not called boostable.
            seen[key] = seen.get(key, True) and boost == 'true'
        for (skill, level), boost in seen.items():
            if boost:
                marks.setdefault(name, {})[skill] = level

    data = json.load(open(DATA, encoding='utf-8'))
    out = {}
    for quest in data['quests']:
        mark = marks.get(quest['name'], {})
        kept = {s: lvl for s, lvl in sorted(quest['skills'].items()) if mark.get(s) == lvl}
        if kept:
            out[quest['name']] = kept
    result = {
        'source': 'Generated by tools/build-boosts.py from Quest Helper (BSD 2-Clause). Do not hand-edit.',
        'quests': out,
    }
    with open(OUT, 'w', encoding='utf-8') as f:
        json.dump(result, f, indent=1, ensure_ascii=False, sort_keys=True)
        f.write('\n')
    print('%d quests, %d boostable requirements' % (len(out), sum(len(v) for v in out.values())))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
