#!/usr/bin/env python3
"""Turns the Fate Locked extraction into the plugin's bundled codex-data.json.

Usage, from the repository root:
  git clone --depth 1 https://github.com/Nubles/OSRS-Fate-Locked tools/OSRS-Fate-Locked
  npx esbuild tools/extract-fate-locked.ts --bundle --platform=node --outfile=build/extract.js
  node build/extract.js > build/fate-locked.json
  python3 tools/build-codex-data.py build/fate-locked.json

Names are rewritten to match net.runelite.api.Quest so quest state can be read
from the client.
"""
import json
import sys

ALIASES = {
    'RFD: Start (The Cook)': "Recipe for Disaster - Another Cook's Quest",
    'RFD: The Cook': "Recipe for Disaster - Another Cook's Quest",
    'RFD: Dwarf': 'Recipe for Disaster - Mountain Dwarf',
    'RFD: Goblins': 'Recipe for Disaster - Wartface & Bentnoze',
    'RFD: Pirate Pete': 'Recipe for Disaster - Pirate Pete',
    'RFD: Lumbridge Guide': 'Recipe for Disaster - Lumbridge Guide',
    'RFD: Evil Dave': 'Recipe for Disaster - Evil Dave',
    'RFD: Skrach Uglogwee': 'Recipe for Disaster - Skrach Uglogwee',
    'RFD: Sir Amik Varze': 'Recipe for Disaster - Sir Amik Varze',
    'RFD: King Awowogei': 'Recipe for Disaster - King Awowogei',
    'RFD: Finale': 'Recipe for Disaster - Culinaromancer',
    'Recipe for Disaster': 'Recipe for Disaster - Culinaromancer',
    'Forgettable Tale of a Drunken Dwarf': 'Forgettable Tale...',
    'Desert Treasure II': 'Desert Treasure II - The Fallen Empire',
}
SKILL_ALIASES = {'Range': 'Ranged'}
QUEST_CAPE = 'Quest Point Cape'


def name(n):
    return ALIASES.get(n, n)


def split_skills(raw):
    skills, qp, combat = {}, 0, 0
    for k, v in raw.items():
        if k == 'Quest Points':
            qp = v
        elif k == 'Combat':
            combat = v
        else:
            skills[SKILL_ALIASES.get(k, k)] = v
    return skills, qp, combat


def main(path):
    src = json.load(open(path))
    out = {
        'source': 'Generated by tools/build-codex-data.py from Nubles/OSRS-Fate-Locked data/. Do not hand-edit.',
        'quests': [],
        'diaries': [],
        'combatAchievementTasks': src['caTiers'],
    }
    for q in src['quests']:
        skills, qp, combat = split_skills(q['skills'])
        out['quests'].append({
            'name': name(q['name']),
            'miniquest': q['kind'] == 'miniquest',
            'points': q['points'],
            'series': q['series'],
            'difficulty': q['difficulty'],
            'skills': skills,
            'questPoints': qp,
            'combatLevel': max(combat, q['combatLevel']),
            'prereqs': [name(p) for p in q['prereqs'] if p != QUEST_CAPE],
        })
    for d in src['diaries']:
        skills, qp, combat = split_skills(d['skills'])
        out['diaries'].append({
            'name': d['id'],
            'area': d['area'],
            'tier': d['tier'],
            'skills': skills,
            'questPoints': qp,
            'combatLevel': combat,
            'allQuests': QUEST_CAPE in d['quests'],
            'quests': [name(p) for p in d['quests'] if p != QUEST_CAPE],
        })
    known = {q['name'] for q in out['quests']}
    unknown = sorted({p for q in out['quests'] for p in q['prereqs'] if p not in known}
                     | {p for d in out['diaries'] for p in d['quests'] if p not in known})
    if unknown:
        print('Untracked requirements (shown as manual checks):', ', '.join(unknown), file=sys.stderr)
    with open('src/main/resources/com/codex/navigator/codex-data.json', 'w') as f:
        json.dump(out, f, indent=1)
        f.write('\n')


if __name__ == '__main__':
    main(sys.argv[1])
